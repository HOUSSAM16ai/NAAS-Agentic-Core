"""سياسة المُنفِّذ الآمن — قائمة السماح والحدود (M0).

المصدر القانوني الوحيد لـ«ما الذي يجوز تنفيذه وبأي حدود». كانت
`ALLOWED_COMMANDS` في `shell_tool.py` **مُعرَّفة ولا تُستخدَم إطلاقاً** — قائمة سماح
ميتة بجوار حارسٍ فعليّ من نوع قائمة منع. هنا تصير القائمة هي الحارس.

**قاعدة دائمة:** الأمان يُفرَض ببنية حتمية لا بمطابقة نصّ. الحقن يُمنع بأن المُنفِّذ
لا يرى **صدفة** أصلاً (`argv` + `shell=False`)، لا بفهرسة أنماط خطرة — فقائمة
الأنماط الخطرة ناقصة دائماً بطبيعتها.
"""

from __future__ import annotations

from dataclasses import dataclass

#: الأوامر المسموح تنفيذها — تُفحَص على `argv[0]` **فعلاً** (M0).
#:
#: مشتقّة من `ALLOWED_COMMANDS` الميتة سابقاً مع حذفين مقصودين:
#: - **`curl`/`wget` خرجتا**: كلتاهما خروج شبكة. الشبكة قدرة تُمنَح صراحةً
#:   (`NETWORK` في عقد الأدوات M1) لا صلاحية افتراضية. أُثبت حيّاً أن `curl`
#:   كانت تخرج إلى الإنترنت فعلاً من هذا المسار.
#: - **`chmod`/`chown` خرجتا**: تعديل صلاحيات ليس حاجةَ أداةِ قراءةٍ، وهو
#:   سُلَّم تصعيد امتيازات كلاسيكي.
ALLOWED_COMMANDS: frozenset[str] = frozenset(
    {
        # قراءة وتصفّح
        "ls",
        "dir",
        "pwd",
        "cat",
        "head",
        "tail",
        "wc",
        "type",
        "more",
        "less",
        "echo",
        # بحث
        "grep",
        "find",
        "rg",
        # سلاسل أدوات المشروع
        "python",
        "python3",
        "pip",
        "pytest",
        "ruff",
        "npm",
        "node",
        "git",
        # كتابة محدودة داخل مساحة العمل
        "mkdir",
        "touch",
        "cp",
        "mv",
    }
)

#: ميتاحروف الصدفة — وجود أيٍّ منها في أمرٍ نصّي يعني أن المتّصل ينوي صياغةَ صدفة،
#: وهو ما لا يدعمه المُنفِّذ. تُرفَض **صراحةً برسالة** لا تُهرَّب بصمت.
SHELL_METACHARACTERS: tuple[str, ...] = (
    ";",
    "|",
    "&",
    "$",
    "`",
    ">",
    "<",
    "\n",
    "\r",
    "(",
    ")",
    "{",
    "}",
)


@dataclass(frozen=True)
class SandboxLimits:
    """حدود موارد العملية الفرعية — تُفرَض بـ`resource` لا بالأمل."""

    #: ثوانٍ من زمن المعالج (يقتل الحلقات اللانهائية).
    cpu_seconds: int = 10
    #: أقصى مساحة عنوان بالبايت (يقتل ابتلاع الذاكرة).
    address_space_bytes: int = 1024 * 1024 * 1024
    #: أقصى عدد عمليات (يقتل قنبلة fork **بنيويّاً**).
    max_processes: int = 64
    #: أقصى حجم ملف يُكتَب.
    file_size_bytes: int = 64 * 1024 * 1024
    #: سقف ما يُقرأ من stdout/stderr — يُطبَّق **أثناء** القراءة.
    max_stdout_bytes: int = 10_000
    max_stderr_bytes: int = 5_000


DEFAULT_LIMITS = SandboxLimits()
