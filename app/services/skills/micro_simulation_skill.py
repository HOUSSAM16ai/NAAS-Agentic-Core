class MicroSimulationSkill:
    """
    خادم المحاكيات المصغّرة الحتمي (D-138 — خادم محتوى L3).

    عقد دائم (لا يُكسر بدون ADR):
    1. حتمي 100% صفر-LLM — الأمثلة ثابتة، لا يخترعها نموذج (نقد MathDial).
    2. قصير جداً ≤320 حرف isomorphic — لا «شرح جديد كامل».
    3. خادم L3 للمصفوفة — يُستدعى حين تقرّر المصفوفة أن الوقت مناسب لمحاكاة مصغّرة.
    """

    _skill_name: str = "micro_simulation"
    doctrine_version: str = MICRO_SIMULATION_DOCTRINE_VERSION

    def get_micro_simulation(self, concept_id: str) -> str | None:
        """يُرجِع المحاكاة المصغّرة للمفهوم (concept_id canonical). None ⇒ لا محاكاة لهذا المفهوم."""
        sim = MICRO_SIMULATIONS.get((concept_id or "").strip())
        if not sim:
            return None
        from app.services.skills.tutor_metrics import record_micro_simulation

        record_micro_simulation(concept_id)
        return sim

    def get_apply_step(self, concept_id: str) -> str | None:
        """يُرجِع سؤال خطوة التطبيق الأولى على التمرين (D-147). None ⇒ لا خطوة لهذا المفهوم."""
        return APPLY_STEPS.get((concept_id or "").strip()) or None


_micro_simulation_singleton: MicroSimulationSkill | None = None


def get_micro_simulation_skill() -> MicroSimulationSkill:
    """يُرجع نسخة مفردة (lazy singleton)."""
    global _micro_simulation_singleton
    if _micro_simulation_singleton is None:
        _micro_simulation_singleton = MicroSimulationSkill()
    return _micro_simulation_singleton


