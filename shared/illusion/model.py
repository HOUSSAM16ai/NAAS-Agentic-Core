"""عقود محرّك فجوة الوهم — حتمية، dep-free (D-212).

لماذا هذه الوحدة موجودة
-----------------------
`bkt_engine` يحسب قناتين — الأداء **المدعوم** والإتقان **الدائم** — ثمّ يستهلكهما
داخلياً. وهناك مستهلك ثالث لم يكن مبنيّاً: **الوليّ**. والإتقان الحقيقي وحده لا يكفيه؛
ما يفهمه في ثلاث ثوانٍ هو **الفرق** بين ما يظنّ ابنه أنه يتقنه وما يتقنه فعلاً. وهذا
الفرق لا يُشتقّ من سؤال، بل من **تاريخ** — وهو بالضبط ما لا يستطيع مساعدٌ عامّ إنتاجه.

القاعدة التي تحمي المصداقية
---------------------------
دون `MIN_OBS` ملاحظةً **غير مدعومة** لا يُصنَّف المفهوم: `classify` تُرجِع ``None``، لا
لوناً ولا خانة. على سابقة ``shared/analytics/retention.py`` حرفياً («الفوج غير الناضج
يُرجِع ``None`` لا صفراً — صفرٌ يقرأ *فقدناهم* والحقيقة *لم يحن الوقت*»). تقريرٌ يلوّن
كلّ المنهاج بعد جلستين **تقريرٌ كاذب**، والوليّ الذي يكتشف ذلك لا يجدّد أبداً.

⛔ **الملاحظات المدعومة لا تُعَدّ.** المحاولة بتلميحٍ أو بلا تأخير هي بالضبط ما يُنتج
الوهم؛ عدُّها دليلَ إتقان يجعل المحرّك يقيس الشيء الذي وُجد ليكشفه.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Final

__all__ = [
    "MIN_OBS",
    "REGISTRY_VERSION",
    "ConceptIllusion",
    "IllusionError",
    "Quadrant",
]

#: إصدار عقد المحرّك. يرتفع مع أي تغيير في معنى حقلٍ أو حدود تصنيف.
REGISTRY_VERSION: Final = "1.0.0"

#: الحدّ الأدنى من الملاحظات **غير المدعومة** قبل أيّ تصنيف.
#: أربعٌ ليست اعتباطاً: دونها يكون المجال الثنائي للنسبة أوسع من المسافة بين الخانات،
#: فيصير اللون ضجيجاً معروضاً بثقة.
MIN_OBS: Final = 4

#: عتبة «مرتفع» على كلا المحورين. واحدة لا اثنتان: عتبتان مختلفتان تجعلان الخانة
#: الحمراء تتمدّد أو تنكمش بلا سببٍ تربوي، وهي الخانة التي يُباع بها المنتج.
_HIGH: Final = 0.60


class IllusionError(ValueError):
    """خرقُ مجالٍ في محرّك فجوة الوهم.

    نرفع ولا نُرجِع قيمةً افتراضية: صفرٌ هنا يُقرأ «لا فجوة» — أي عكس الحقيقة تماماً
    (CLAUDE.md §0: المجهول أفضل من يقين زائف).
    """


class Quadrant(StrEnum):
    """التصنيف الرباعي — وهو المخرَج الذي يفهمه الوليّ بلا شرح."""

    #: 🟢 ثقة مرتفعة × إتقان مرتفع — لا تُضِع وقتاً هنا.
    MASTERED = "mastered"
    #: 🔴 ثقة مرتفعة × إتقان منخفض — **المنتج**. ليست فجوة معرفة بل معرفة خاطئة راسخة،
    #: وهي التي تُسقِط يوم الامتحان لأن صاحبها لا يراجعها أصلاً.
    DANGEROUS = "dangerous"
    #: 🔵 ثقة منخفضة × إتقان مرتفع — يحتاج ثقةً لا تعليماً.
    HIDDEN_SKILL = "hidden_skill"
    #: 🟠 ثقة منخفضة × إتقان منخفض — الحالة السهلة، والفجوة معلومة لصاحبها.
    KNOWN_GAP = "known_gap"


@dataclass(frozen=True, slots=True)
class ConceptIllusion:
    """قياس فجوة الوهم لمفهومٍ واحد. يُبنى عبر ``engine.classify`` وحده."""

    #: من ``shared/curriculum`` — لا مصدر ثانٍ للمُعرَّفات (D-193).
    concept_id: str
    #: الثقة المُعلَنة قبل الإجابة [0,1]. بعدها تتلوّث بالنتيجة فلا تقيس شيئاً.
    confidence: float
    #: الإتقان الدائم غير المدعوم، مضروباً في قابلية الاسترجاع [0,1].
    durable_mastery: float
    #: `confidence − durable_mastery` ∈ [-1,1]. الموجب وهمٌ، والسالب مهارةٌ مخفيّة.
    gap: float
    quadrant: Quadrant
    #: عدد المحاولات **غير المدعومة** التي بُني عليها القياس.
    observations: int

    @property
    def is_dangerous(self) -> bool:
        """الخانة الحمراء — «واثقٌ ومخطئ»."""
        return self.quadrant is Quadrant.DANGEROUS


def quadrant_for(confidence: float, durable_mastery: float) -> Quadrant:
    """يُحدّد الخانة من المحورين. مُستخرَجة كي يبقى للحدود موطنٌ واحد."""
    confident = confidence >= _HIGH
    mastered = durable_mastery >= _HIGH
    if confident:
        return Quadrant.MASTERED if mastered else Quadrant.DANGEROUS
    return Quadrant.HIDDEN_SKILL if mastered else Quadrant.KNOWN_GAP
