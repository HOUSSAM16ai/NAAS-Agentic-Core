"""تأليف الرسالة — من كتب هذا النصّ فعلاً؟ (D-229)

## لماذا هذه الوحدة موجودة

هجوم **حقن الذاكرة (MINJA)** يعمل بزرع تعليمةٍ اليوم تُقرَأ بعد أسابيع كأنها كلام
المستخدم. ونسبة نجاحه الموثَّقة تتجاوز 95٪. وخطره الحقيقي في **تأجيل التفعيل**: لا شيء
يبدو معطوباً لحظةَ الزرع.

**وهذا المستودع نفّذ الهجوم على نفسه.** في نافذة يونيو 2026 كُتب النصّ الداخلي
«[توجيه تربوي] الطالب ما زال يبني هذا المفهوم…» في جدول رسائل الإنتاج **٢٨ مرّة بدور
`user`**. فصارت تعليماتُ النظام مُخزَّنةً كأنها كلام الطالب، تُقرأ في كل دورٍ لاحق كدليلٍ
من المحادثة. والطالب لم يقل شيئاً من ذلك.

النتيجة المزدوجة: تسمّم التوجيه (كاشفُ النيّة يقرأ كلامَ النظام كنيّةٍ للطالب — خرق
D-102)، وتسريب هندسة التعليم إلى الطالب (خرق D-117).

## القاعدة

⛔ **لا نصٍّ يُولِّده النظام يُكتب أبداً بدورٍ يخصّ الطالب.** توجيه النظام يسافر في قناة
النظام أو في وسائط مُهيكَلة — لا في صفٍّ يقول إن الطالب قاله.

## لماذا قائمة العلامات هنا وحدها

مصدرٌ واحد (D-013/D-193): علامةٌ تُعرَّف في موضعين تتفرّق النسختان، فيصير مسارٌ يحجب
ومسارٌ **يسرّب** — والطالب لا يعرف أيّ عقلٍ خزّن كلامه. تحرس الوحدةَ بوّابةُ
`scripts/fitness/check_no_system_text_as_user.py`.
"""

from __future__ import annotations

import re
from typing import Final

__all__ = [
    "SYSTEM_AUTHORED_MARKERS",
    "MemoryAuthorshipError",
    "assert_student_authored",
    "is_system_authored",
    "strip_system_markers",
]


class MemoryAuthorshipError(ValueError):
    """نصٌّ من تأليف النظام حاول أن يُخزَّن بدور الطالب.

    ⛔ لا يُرجَع صفرٌ ولا `False` صامتة هنا: الكتابة الخاطئة في الذاكرة الحلقية
    **مؤجَّلة الأثر**، فالفشل يجب أن يكون صريحاً عند الزرع لا عند القراءة بعد أسابيع.
    """


#: العلامات التي تدلّ قطعاً على نصٍّ من تأليف النظام.
#:
#: كلٌّ منها **مأخوذ من عطلٍ حيّ** لا من تخيّل:
#:   «[توجيه تربوي]»      — ٢٨ صفّاً بدور `user` في الإنتاج (ISS-146)
#:   «⟦…⟧»                — ١٣ تسريباً لعلامةٍ داخلية (نافذة يونيو 2026)
#:   «[وضع الشرح العميق]» — يُسبَق للسؤال في MODE_B؛ مسموحٌ على السلك، ⛔ ممنوعٌ في التخزين
#:   «WARM-UP:»           — ١٩٠٢ حرفاً من نصّ نظامٍ إنجليزي وصلت طالباً في ضائقة
SYSTEM_AUTHORED_MARKERS: Final[tuple[str, ...]] = (
    "[توجيه تربوي]",
    "التوجيه التربوي",
    "[وضع الشرح العميق]",
    "مثال_محلول",
    "تفعيل الفهم المبكر",
    "WARM-UP:",
    "WARM‑UP:",
)

#: العلامات المُحيطة الداخلية (‏U+27E6/U+27E7) — أيّ ورودٍ لها تأليفُ نظام.
_SENTINEL = re.compile(r"[⟦⟧]")

#: يُستعمل للتقليم لا للحكم: العلامة قد تُسبَق بمسافاتٍ أو سطرٍ جديد.
_LEADING_WS = re.compile(r"^\s+")


def is_system_authored(content: str | None) -> bool:
    """هل يحمل النصّ علامةَ تأليفٍ من النظام؟

    الفحص على **ورود العلامة في أيّ موضع** لا على البادئة وحدها: النصّ المُسرَّب في
    الإنتاج ظهر مرّةً في البداية ومرّةً بعد سطرٍ فارغ، وحارسُ البادئة وحده كان سيمرّ.
    """
    if not content:
        return False
    if _SENTINEL.search(content):
        return True
    return any(marker in content for marker in SYSTEM_AUTHORED_MARKERS)


def strip_system_markers(content: str) -> str:
    """يحذف علامات تأليف النظام ويُعيد ما تبقّى مُقلَّماً.

    ⚠️ للعرض والقياس فقط. ⛔ **ليست بديلاً عن المنع**: نصٌّ نُزعت علامته يبقى نصَّ
    نظامٍ في جوهره، وتخزينُه بدور الطالب يبقى تسميماً — الفرق أنه صار غير مرئي.
    """
    cleaned = _SENTINEL.sub("", content)
    for marker in SYSTEM_AUTHORED_MARKERS:
        cleaned = cleaned.replace(marker, "")
    return _LEADING_WS.sub("", cleaned).strip()


def assert_student_authored(content: str | None, *, where: str) -> None:
    """يمنع تخزين نصّ نظامٍ بدور الطالب. يرفع `MemoryAuthorshipError` عند المخالفة.

    Args:
        content: النصّ المُراد تخزينه بدور الطالب.
        where: موضع النداء — يظهر في الرسالة كي يُشخَّص المصدر بلا تتبّعٍ يدوي.
    """
    if not is_system_authored(content):
        return
    preview = (content or "")[:80].replace("\n", " ")
    raise MemoryAuthorshipError(
        f"{where}: محاولةُ تخزين نصٍّ من تأليف النظام بدور الطالب — {preview!r}.\n"
        "الذاكرة الحلقية تحفظ ما قاله الطالب فعلاً. نصُّ النظام يسافر في قناة النظام "
        "أو في وسائط مُهيكَلة (D-229/ISS-146)."
    )
