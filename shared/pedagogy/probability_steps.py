"""علامات خطوات التدريس الاحتمالي — المصدر القانوني للعقلين (D-206 · L5).

## الكارثة التي يُغلقها هذا الملفّ

المونوليث (`app/services/skills/probability_brain/cognitive_verification.py`) والخدمة
(`microservices/orchestrator_service/.../overmind/probability_tutor.py`) يحملان **نفس**
علامات الخطوة منسوخةً حرفياً. وهي ليست تفصيلاً تجميلياً: بها يُقرَّر

- **هل بدأ الحوار التدريسي؟** (فلا يُعاد probe التشخيص الأول)، و
- **أيّ سؤالٍ معلَّق يُقاس عليه جوابُ الطالب؟** (فيُعترَف بإجابته الصحيحة).

أي أنّ انحرافَ علامةٍ واحدة يعني **عقلاً يعترف بإجابة الطالب وعقلاً يتجاهلها**، والطالب
لا يعرف أيّهما أجابه (نفس منطق D-203 في تكافؤ الحجب).

**والانحراف وقع فعلاً، لا نظرياً.** عند مسح النسختين وجدتُ أنّ نسخة الخدمة تحمل
``"لنبدأ من فهمك أنت"`` ضمن `TUTORING_STEP_MARKERS` ونسخةَ المونوليث **لا تحملها** —
وهي نصّ probe الافتتاح نفسه. فالمونوليث لا يتعرّف على probe بثّه هو، فيجوز أن يُعيده
بعد أن بدأ التدريس: وهو بالضبط صنفُ التكرار الذي وُلدت D-155 لقتله.

## القاعدة الدائمة (L5)

> **منطقٌ يقرّر مصير دور الطالب لا يعيش في عقلين بلا تكافؤٍ محروس.**

مصدرٌ واحد هنا، ونسخةٌ مُوَرَّدة في الخدمة (دستور الخدمات: صفر استيراد من ``shared/`` —
مُتحقَّق: لا استيراد واحد في الشجرة كلّها)، وبوّابة ``check_probability_brain_parity``
تُثبت تطابقهما في الاتجاهين. نمط ``shared/notation`` المُثبَت (D-185).

⛔ **الاتحاد لا التقاطع** (D-186#2): علامةٌ يعرفها عقلٌ واحد تصير معروفةً للعقلين.
حذفُ علامةٍ من هنا يتطلّب دليلاً على أنها تُنتج ضرراً، لا مجرّد أنها «زائدة».

## بلا تبعيات

stdlib فقط — لتصلح للتوريد بلا سلسلة استيراد.
"""

from __future__ import annotations

from typing import Final

__all__ = [
    "FIRST_HELP_MARKERS",
    "STEP_QUESTION_MARKERS",
    "TUTORING_STEP_MARKERS",
    "pending_step_for",
    "started_tutoring",
]

#: قوالب أسئلة الخطوات التي يطرحها المعلّم — تُعرِّف «السؤال المعلَّق» المشتقّ من أحدث
#: رسالة مساعد (ISS-122 · D-155). أي قالب سؤالٍ جديد في البُناة الحتمية **يجب** أن
#: يُسجَّل هنا، وإلّا صار سؤاله غير مرئيّ للتحقّق فتُهمَل إجابةُ الطالب الصحيحة عليه.
STEP_QUESTION_MARKERS: Final[tuple[tuple[str, str], ...]] = (
    ("كم عدد **كل** الطرق الممكنة", "denominator"),
    ("كم عدد كل الطرق الممكنة", "denominator"),
    ("كيف تُكوّن منهما الاحتمال", "ratio"),
    ("فما قيمة P(A)", "ratio"),
    ("ما قيمة P(A) التي حصلت عليها", "ratio"),
    ("أيّ الألوان يمكن أن تعطينا", "colors"),
)

#: علامات «خطوة تدريس سابقة» — وجود أيٍّ منها في رسائل المساعد يعني أن الحوار التدريسي
#: بدأ (فلا يُعاد probe التشخيص الأول). D-155/D-163.
#:
#: ``"لنبدأ من فهمك أنت"`` كانت في نسخة الخدمة وحدها — انظر رأس الملفّ. إدراجُها هنا
#: هو **الاتحاد** المطلوب: probe الافتتاح خطوةُ تدريسٍ بحكم كونه ما يبدأ به التدريس.
TUTORING_STEP_MARKERS: Final[tuple[str, ...]] = (
    "الحالات الملائمة",
    "كم عدد **كل** الطرق",
    "كيف تُكوّن منهما الاحتمال",
    "أيّ الألوان يمكن أن تعطينا",
    "لنُكمل معاً خطوة بخطوة",
    "فما قيمة P(A)",
    "لنبدأ من فهمك أنت",
)

#: أول طلب مساعدة عامّ يستحق probe التشخيص قبل أي محتوى محسوب (D-155).
FIRST_HELP_MARKERS: Final[tuple[str, ...]] = (
    "كيف افهم",
    "كيف نفهم",
    "كيف احل",
    "كيف نحل",
    "من اين ابدا",
    "من اين نبدا",
    "كيف ابدا",
    "كيف نبدا",
)


def started_tutoring(assistant_texts: tuple[str, ...]) -> bool:
    """هل بُثّت أيّ خطوة تدريس سابقاً؟ (منطقٌ واحد للعقلين، لا مطابقةٌ مُعادة)."""
    return any(marker in text for text in assistant_texts for marker in TUTORING_STEP_MARKERS)


def pending_step_for(assistant_text: str) -> str | None:
    """مُعرَّف الخطوة التي سألنا عنها الطالب في هذا النصّ، أو ``None``.

    الأطول أوّلاً: ``"كم عدد **كل** الطرق الممكنة"`` تحتوي ``"كم عدد كل الطرق الممكنة"``
    بعد تجريد التشديد، فترتيبُ الطول يمنع خطفَ العامّ للخاصّ (سابقة `shared/curriculum`).
    """
    if not assistant_text:
        return None
    for marker, step in sorted(STEP_QUESTION_MARKERS, key=lambda item: -len(item[0])):
        if marker in assistant_text:
            return step
    return None
