"""ميزانيات الإدراك — كم ينتظر الطالب قبل أن ينكسر التعلّم (D-230)

## العطل المقيس الذي وُلدت منه هذه الوحدة

قياسٌ حيّ على قاعدة الإنتاج (2026-08-08 · **1371** دوراً منذ 2026-05-01)، زمنُ الوصول
إلى أوّل ردٍّ غير فارغ:

    p50   7.57 ثانية
    p75  28.64 ثانية
    p95  72.57 ثانية
    فوق ١٠ ثوانٍ   533 دوراً (38.9٪)
    بلا ردٍّ أصلاً   91 دوراً (6.6٪)

## الأرقام ليست ذوقاً

- **٤٠٠ms — عتبة Doherty** (‏Brady، *IBM Systems Journal*، 1982): تحت هذا الحدّ يبقى
  المستخدم في حالة تدفّق، وفوقه تنهار إنتاجيّته بقفزة لا بتدرّج.
- **حدود Nielsen الثلاثة** (1993، وما زالت المرجع): ‏0.1s يُقرأ **فوريّاً** · 1s يحفظ
  **تدفّق التفكير** · **10s حدّ الانتباه** — بعدها يذهب الذهن إلى شيءٍ آخر.

والأثر التعليمي أخصّ من الأثر العام: الطالب الذي ينتظر ثماني ثوانٍ **يفقد الخيط الذي
كان يبنيه**، فيعود إلى إجابةٍ لا إلى تفكيرٍ متّصل — وهو عكسُ ما تقيسه فجوة الوهم.

## لماذا الأرقام هنا لا في النثر

قاعدة D-192: أيّ عددٍ قابل للتغيّر **يُشتَقّ من مصدره ولا يُكتب في النثر**، والكمّية
الواحدة لا تحمل قيمتين في موضعين. فهذه الوحدة هي الموطن، والتقارير والمقاييس تقرأ منها.

⛔ **ولا تُرفَع هذه الحدود لتمرير قياسٍ سيّئ.** الحدّ يصف الإدراك البشري لا قدرتنا
الحالية؛ ورفعه يعني تغيير المسطرة لا تحسين المنتج (D-209 الطبقة ٩: رفعُ مِسنَنٍ مُعلَن
قرارٌ مكتوب يُسمّي سببه).
"""

from __future__ import annotations

from enum import StrEnum
from typing import Final

__all__ = [
    "ATTENTION_LIMIT_S",
    "FIRST_OBJECT_PAINT_MS",
    "FLOW_LIMIT_S",
    "INSTANT_LIMIT_MS",
    "LatencyVerdict",
    "classify_latency",
]

#: يُقرأ فوريّاً — لا يلاحظ المستخدم انتظاراً (Nielsen).
INSTANT_LIMIT_MS: Final[int] = 100

#: عتبة Doherty: أوّل كائنٍ تفاعلي يجب أن يُرسَم قبلها.
#:
#: هذا هو الحدّ الذي يخدمه «الجواب قبل التفكير»: الطبقات الحتمية (التحية · سجلّ الرموز ·
#: العقل الاحتمالي · `enrich_node`) لا تحتاج نموذجاً لغوياً وتُنتج في مللي ثوانٍ، فتُلوّن
#: بنيةَ الدور فوراً بينما يلحق السرد.
FIRST_OBJECT_PAINT_MS: Final[int] = 400

#: يحفظ تدفّق التفكير — فوقه يشعر الطالب بالانتظار وإن لم يشتكِ.
FLOW_LIMIT_S: Final[float] = 1.0

#: حدّ الانتباه — بعده يذهب الذهن إلى شيءٍ آخر ويُفقَد الخيط.
ATTENTION_LIMIT_S: Final[float] = 10.0


class LatencyVerdict(StrEnum):
    """حكمٌ مُصرَّح على زمن الدور — لا رقمٌ عارٍ يُفسَّر في كل موضعٍ بطريقة."""

    INSTANT = "instant"
    FLOWING = "flowing"
    NOTICEABLE = "noticeable"
    ATTENTION_LOST = "attention_lost"


class BudgetError(ValueError):
    """زمنٌ غير صالح. ⛔ لا يُرجَع حكمٌ متفائل عن مُدخَلٍ فاسد (§0: لا صفر مضلِّل)."""


def classify_latency(seconds: float) -> LatencyVerdict:
    """يُصنِّف زمن انتظارٍ مقابل الحدود المُعلَنة.

    Args:
        seconds: الزمن بالثواني. سالبٌ أو غير رقمي ⇒ `BudgetError`.

    Raises:
        BudgetError: زمنٌ سالب — قياسٌ فاسد يُعلَن ولا يُصنَّف «فوريّاً» بالخطأ.
    """
    if seconds < 0:
        raise BudgetError(f"زمنٌ سالب ({seconds}) — قياسٌ فاسد لا يُصنَّف.")
    if seconds * 1000 <= INSTANT_LIMIT_MS:
        return LatencyVerdict.INSTANT
    if seconds <= FLOW_LIMIT_S:
        return LatencyVerdict.FLOWING
    if seconds < ATTENTION_LIMIT_S:
        return LatencyVerdict.NOTICEABLE
    return LatencyVerdict.ATTENTION_LOST
